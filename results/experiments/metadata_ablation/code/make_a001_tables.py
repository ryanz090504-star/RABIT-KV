"""Generates the A001 appendix table (LaTeX) and a flat number sheet from the INDEPENDENTLY recomputed analysis
(independent-audit.json). Runs only if that audit passed. argv: <independent-audit.json> <out dir>"""
import json, sys
from pathlib import Path
ia = json.loads(Path(sys.argv[1]).read_text()); out = Path(sys.argv[2]); out.mkdir(parents=True, exist_ok=True)
if not ia['passed']:
    # Only allowed exception (documented in the run record, as in H001R): the byte-equality cross-check between the Pod's
    # audit and the local re-run fails at the last floating-point bit (Linux vs Windows libm); every validity check passed.
    failed = [k for k, v in ia['checks'].items() if not (v if isinstance(v, bool) else all(v.values()))]
    ulp = json.loads((Path(sys.argv[1]).parent / 'pod-vs-local-ulp.json').read_text())
    assert failed == ['pod_audit_equals_local_audit'] and ulp['max_rel'] < 1e-12 and ulp['all_integer_and_count_fields_equal'], \
        ('independent audit did not pass: no tables', failed)
NAMES = {'llama3_1_8b': 'Llama-3.1-8B', 'qwen2_5_7b': 'Qwen2.5-7B'}
ARMS = [('bf16', 'BF16'), ('rabit', 'Frozen policy'), ('range_real', 'Padding excluded'), ('meta_exact', 'Exact metadata'),
        ('range_meta_exact', 'Padding excl.\\ + exact metadata')]
CON = [('meta_exact_vs_rabit', 'Exact metadata vs.\\ frozen'), ('range_meta_exact_vs_range_real', 'Padding excl.\\ + exact metadata vs.\\ padding excl.'),  # R11: was mislabelled 'Exact metadata vs. padding excl.'
       ('range_real_vs_rabit', 'Padding excl.\\ vs.\\ frozen')]
f2 = lambda x: f'{x:.3f}' if x < 100 else f'{x:.2f}'
sg = lambda x: ('+' if x >= 0 else '$-$') + f'{abs(x):.2f}'
sheet = {}
L = [r'% generated by ablation-a001/tools/make_a001_tables.py from independent-audit.json; do not edit by hand',
     r'\begin{tabular}{@{}lrr@{}}', r'\toprule', r' & Llama-3.1-8B & Qwen2.5-7B \\', r'\midrule', r'\multicolumn{3}{@{}l}{\emph{Perplexity, 32 windows}} \\']
mm = ['llama3_1_8b', 'qwen2_5_7b']
for a, lab in ARMS:
    L.append(f'{lab} & ' + ' & '.join(f2(ia['models'][m]['analysis_recomputed']['ppl'][a]) for m in mm) + r' \\')
    for m in mm:
        sheet[f'{m}.ppl.{a}'] = ia['models'][m]['analysis_recomputed']['ppl'][a]
L.append(r'\midrule'); L.append(r'\multicolumn{3}{@{}l}{\emph{Paired change in perplexity, \% [95\% CI]; windows worse/better}} \\')
for c, lab in CON:
    cells = []
    for m in mm:
        x = ia['models'][m]['analysis_recomputed']['contrasts'][c]
        cells.append(f"{sg(x['ppl_change_pct'])} [{sg(x['ci95_pct'][0])}, {sg(x['ci95_pct'][1])}]; {x['windows_worse']}/{x['windows_better']}")
        sheet[f'{m}.{c}'] = x
    L.append(f'{lab} & ' + ' & '.join(cells) + r' \\')
L += [r'\bottomrule', r'\end{tabular}']
(out / 'a001-table.tex').write_text('\n'.join(L) + '\n', encoding='utf-8')
for m in mm:
    for k in ['meta8_share_of_frozen_excess', 'meta8_share_of_padding_excluded_excess']:
        sheet[f'{m}.{k}'] = ia['models'][m]['analysis_recomputed'][k]
(out / 'a001-numbers.json').write_text(json.dumps(sheet, indent=2), encoding='utf-8')
print('\n'.join(L)); print(json.dumps({k: v for k, v in sheet.items() if 'share' in k}, indent=1))
