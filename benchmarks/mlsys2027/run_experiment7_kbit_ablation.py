"""
RABIT-KV MLSys 2027 -- Experiment 7 runner: single-axis K-bit ablation (P0-D), LOGICAL fake-quant QUALITY only.

Varies ONLY key precision around the frozen final RABIT policy (rabit2 = K3 seq_affine G32 / V2 group_affine G32 /
R4 / META int8 g64). Conditions:
    rabit2_k2  K2 V2 G32 R4 META8g64
    rabit2     K3 V2 G32 R4 META8g64   (control, the unchanged canonical config)
    rabit2_k4  K4 V2 G32 R4 META8g64
plus the bf16 reference row (uncompressed; not an ablation condition -- niah.py always evaluates it first and
every script reports compression / deltas against it).

This is NOT a physical serving benchmark: no allocator capacity, throughput or latency is reported. KV numbers are
LOGICAL packed-prefix accounting (payload bits + uint8-group metadata + BF16 residual), see logical_kv_bytes().

Code path: the canonical benchmarks/quality/*.py are NOT edited (Experiment 1 / 2 runners pin their text). The
runner executes deterministic Experiment 7 copies in benchmarks/mlsys2027/exp7_kbit/ generated by
exp7_kbit_scripts.py (only: provenance header, Modal App name, allowed set, and two config_for_method branches
that copy rabit2 and replace k_bits). Workloads, sample counts, seeds and all other code are the canonical ones
(Experiment 1 RUNS, --methods changed only).

Usage:
    python benchmarks/mlsys2027/run_experiment7_kbit_ablation.py --dry-run
    python benchmarks/mlsys2027/run_experiment7_kbit_ablation.py            (NOT until explicitly authorized)
"""

