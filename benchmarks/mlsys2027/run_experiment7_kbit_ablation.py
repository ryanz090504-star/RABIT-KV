import exp7_kbit_scripts as gen  # noqa: E402
import run_experiment1_quality_frontier as e1  # noqa: E402  (accepted Exp1 runner: reused, not modified)

ROOT = e1.ROOT
RUNNER_SCRIPT = Path(__file__).resolve()
OUT_DIR = ROOT / "results" / "mlsys2027" / "ablations" / "k_bit"
MANIFEST = OUT_DIR / "manifest.json"
REGRESSION_CHECK = OUT_DIR / "regression_check.json"
RESULTS = OUT_DIR / "kbit_results.json"
METHODS = "bf16,rabit2_k2,rabit2,rabit2_k4"
CONDITIONS = {"rabit2_k2": 2, "rabit2": 3, "rabit2_k4": 4}  # method -> k_bits; everything else frozen
FROZEN = {"v_bits": 2, "k_style": "seq_affine", "v_style": "group_affine", "k_group": 32, "v_group": 32,
          "residual": 4, "metadata_mode": "int8", "metadata_group_size": 64}
EXP6_FROZEN_COMMIT = "0f5f6efa7cfdf0b7add27521270e91246ec4c191"
EXP6_DIR = ROOT / "results" / "mlsys2027" / "concurrency_scaling"
PROTECTED_PATHS = [*e1.PROTECTED_PATHS, ROOT / "benchmarks" / "quality",
                   *[ROOT / "results" / "mlsys2027" / d for d in (
                       "quality_frontier", "multilingual_frontier", "concurrency_scaling", "concurrency_smoke",
                       "context_scaling", "deployment", "fp8_baseline", "diagnostics")]]
# Which whitespace-split columns of each script's printed summary row hold (quality metric, avg logical KV MB);
# identical to the accepted Experiment 1 regression parser.
ROW_COLUMNS = {"continuation_ppl": ("ppl", 1, 4), "niah": ("accuracy_pct", 3, 4),
               "passage_retrieval": ("accuracy_pct", 1, 3), "hotpotqa": ("f1_pct", 1, 3), "qasper": ("f1_pct", 1, 3)}
# K payload is exactly linear in k_bits (codes.numel() is a multiple of 8), so for every benchmark
# KV(K4) - KV(K3) == KV(K3) - KV(K2) up to the scripts' 3-decimal print rounding.
LINEARITY_ABS_TOL_MB = 0.002

# Llama-3.1-8B KV geometry used by the logical accounting model.
LAYERS, KV_HEADS, HEAD_DIM = 32, 8, 128


def _meta_bytes(n: int, group: int = 64) -> int:
    """uint8-group metadata (encode_metadata): codes padded to the group, plus BF16 min and scale per group."""
    npad = math.ceil(n / group) * group
    return npad + 4 * (npad // group)


def logical_kv_bytes(prefix_tokens: int, k_bits: int, v_bits: int = 2, residual: int = 4, group: int = 32) -> dict:
    """Logical packed prefix-KV bytes of the rabit2-family policy for ONE sequence (batch 1), all layers.
    K: seq_affine (groups of `group` tokens per channel, sequence padded to the group); V: group_affine along
    head_dim; the last `residual` tokens stay BF16; payload = ceil(codes * bits / 8)."""
    T = prefix_tokens
    if T <= residual:
        bf16 = LAYERS * 2 * T * KV_HEADS * HEAD_DIM * 2
        return {"k_payload": 0, "k_meta": 0, "v_payload": 0, "v_meta": 0, "residual": bf16, "total": bf16}
    lq = T - residual
    lk = math.ceil(lq / group) * group
    k_payload = math.ceil(KV_HEADS * lk * HEAD_DIM * k_bits / 8)
    k_meta = 2 * _meta_bytes(KV_HEADS * (lk // group) * HEAD_DIM)
    v_payload = math.ceil(KV_HEADS * lq * HEAD_DIM * v_bits / 8)
    v_meta = 2 * _meta_bytes(KV_HEADS * lq * (HEAD_DIM // group))
    resid = 2 * residual * KV_HEADS * HEAD_DIM * 2
    per_layer = {"k_payload": k_payload, "k_meta": k_meta, "v_payload": v_payload, "v_meta": v_meta,
                 "residual": resid}
    out = {k: LAYERS * v for k, v in per_layer.items()}
    out["total"] = sum(out.values())
    return out


def runs() -> list[dict]:
    """Experiment 1's RUNS verbatim, with --methods replaced and the script taken from the Exp7 derived copies."""
    out = []
    for spec in e1.RUNS:
        args = list(spec["args"])
        i = args.index("--methods")
        args[i + 1] = METHODS
        out.append({"name": spec["name"], "script": gen.derived_path(spec["name"]), "args": args,
                    "purpose": spec["purpose"].replace("bf16/rabit8/rabit4/rabit3/rabit2 frontier",
                                                       "K-bit ablation").replace("full frontier", "K-bit ablation")})
    return out


def protected_status() -> str:
    return e1.run_git("status", "--short", "--", *[str(p.relative_to(ROOT)) for p in PROTECTED_PATHS])


def preflight(dry_run: bool) -> dict:
    status = protected_status()
    if status:
        raise RuntimeError("protected paths are not clean:\n" + status)
    if e1.sha256(e1.RABIT_KV2) != e1.EXPECTED_RABIT_SHA256:
        raise RuntimeError("rabit_kv2.py is not the frozen source")
    if e1.run_git("diff", "--name-only", EXP6_FROZEN_COMMIT, "--", str(EXP6_DIR.relative_to(ROOT))):
        raise RuntimeError("accepted Experiment 6 evidence differs from its frozen commit")
    gen_ok = gen.check()
    if not all(gen_ok.values()):
        raise RuntimeError(f"Exp7 derived scripts differ from their derivation: {gen_ok}")
    for b in gen.BENCHMARKS:  # the canonical scripts still carry the text the Exp1 runner pins
        text = gen.canonical_path(b).read_text(encoding="utf-8")
        if e1.REQUIRED_ALLOWED_LINE not in text or e1.REQUIRED_RABIT2_MARKER not in text:
            raise RuntimeError(f"canonical {b}.py no longer matches the accepted Experiment 1 pins")
    e1.verify_canonical_reference()
    uncommitted = e1.run_git("status", "--short", "--", *[str(p.relative_to(ROOT)) for p in (
        RUNNER_SCRIPT, gen.DERIVED_DIR, HERE / "exp7_kbit_scripts.py", HERE / "test_experiment7_kbit.py")])
    if uncommitted and not dry_run:
        raise RuntimeError("Refusing to run: Experiment 7 harness has uncommitted changes:\n" + uncommitted)
    if MANIFEST.exists() and json.loads(MANIFEST.read_text(encoding="utf-8")).get("status") == "passed":
        raise RuntimeError(f"{MANIFEST} already records a passed run; refusing to overwrite")
    return {"git_head": e1.run_git("rev-parse", "HEAD"), "rabit_kv2_sha256": e1.EXPECTED_RABIT_SHA256,
            "exp6_frozen_commit": EXP6_FROZEN_COMMIT,
            "canonical_script_sha256": {b: e1.sha256(gen.canonical_path(b)) for b in gen.BENCHMARKS},
            "derived_script_sha256": {b: e1.sha256(gen.derived_path(b)) for b in gen.BENCHMARKS},
            "runner_script_sha256": e1.sha256(RUNNER_SCRIPT), "uncommitted_files": uncommitted or None}


def build_commands() -> list[dict]:
    return [{"name": r["name"], "purpose": r["purpose"],
             "command": [sys.executable, "-m", "modal", "run", str(r["script"]), *r["args"]],
             "log": (OUT_DIR / f"{r['name']}.log").relative_to(ROOT).as_posix()} for r in runs()]


def parse_rows(name: str, log_text: str) -> dict:
    metric, qi, mi = ROW_COLUMNS[name]
    out = {}
    for method in ("bf16", *CONDITIONS):
        tokens = e1._last_row_tokens(log_text, method)
        out[method] = None if tokens is None or len(tokens) <= max(qi, mi) else {
            metric: float(tokens[qi]), "avg_logical_kv_mb": float(tokens[mi])}
    return out


def integrity(name: str, rc: int, log_text: str) -> dict:
    rows = parse_rows(name, log_text)
    checks = {"exit_code_zero": rc == 0, "no_traceback": "Traceback (most recent call last)" not in log_text,
              "all_four_rows_present": all(rows.values())}
    if checks["all_four_rows_present"]:
        k2, k3, k4 = (rows[m]["avg_logical_kv_mb"] for m in ("rabit2_k2", "rabit2", "rabit2_k4"))
        checks["kv_mb_strictly_increasing_in_k_bits"] = k2 < k3 < k4
        checks["kv_mb_linear_in_k_bits"] = abs((k4 - k3) - (k3 - k2)) <= LINEARITY_ABS_TOL_MB
    reg = e1.check_regression(name, log_text)  # bf16 + K3 control vs the canonical reference (Exp1 tolerances)
    checks["bf16_and_k3_control_reproduce_canonical"] = reg["all_within_tolerance"]
    return {"benchmark": name, "rows": rows, "checks": checks, "regression": reg,
            "passed": all(checks.values())}


def main(argv: list[str] | None = None) -> int:
    e1.make_console_encoding_safe()
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)
    prov = preflight(a.dry_run)
    print("RABIT-KV MLSys 2027 -- Experiment 7 K-bit ablation (logical fake-quant quality)")
    print("Preflight OK:", json.dumps({k: prov[k] for k in ("git_head", "exp6_frozen_commit")}))
    for c in build_commands():
        print(f"  {c['name']}: {' '.join(c['command'][3:])}")
    if prov["uncommitted_files"]:
        print("  WARNING (dry-run only): uncommitted:\n    " + prov["uncommitted_files"].replace("\n", "\n    "))
    if a.dry_run:
        print("\n--dry-run: nothing executed, no files written.")
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    manifest = {"experiment": "Experiment 7 -- K-bit ablation (logical fake-quant quality)", "methods": METHODS,
                "conditions_k_bits": CONDITIONS, "frozen": FROZEN, "status": "running",
                "started_utc": dt.datetime.now(dt.timezone.utc).isoformat(), "provenance": prov, "runs": []}
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    results = []
    for c in build_commands():
        log = ROOT / c["log"]
        rc = e1.stream_command(c["command"], log)
        res = integrity(c["name"], rc, log.read_text(encoding="utf-8", errors="replace"))
        results.append(res)
        manifest["runs"].append({"name": c["name"], "returncode": rc, "passed": res["passed"],
                                 "log_sha256": e1.sha256(log)})
        MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        if not res["passed"]:  # no retry; stop at the first failing benchmark
            break
    REGRESSION_CHECK.write_text(json.dumps([r["regression"] for r in results], indent=2) + "\n", encoding="utf-8")
    RESULTS.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    ok = len(results) == len(e1.RUNS) and all(r["passed"] for r in results) and not protected_status()
    manifest.update(status="passed" if ok else "failed",
                    completed_utc=dt.datetime.now(dt.timezone.utc).isoformat())
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"\nEXPERIMENT 7 {manifest['status'].upper()}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
