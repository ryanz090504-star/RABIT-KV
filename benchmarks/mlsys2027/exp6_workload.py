"""
MLSys 2027 Experiment 6 -- frozen workload definition (pure Python; no vLLM, no
torch, no tokenizer). Imported by the in-container worker AND by the local
runner / tests, so the prompt set is generated by exactly the same code
everywhere and its hashes can be frozen before any run.

Prompts are token-ID sequences (tokenizer-independent): BOS (128000, Llama-3.1)
followed by pseudo-random ordinary vocabulary IDs in [1000, 30000) derived from
SHA-256(tag:length:index:position) -- deterministic, distinct per index, no
special tokens. For each prompt length there is ONE fixed ordered set of 256
measured prompts and ONE fixed set of 2 warmup prompts (distinct from them).

COMPILE-CONDITIONING AMENDMENT (reviewed, after the JIT-contaminated L2048
attempt 1 and before any rerun): for every prompt length x concurrency C there is
ONE fixed set of exactly C conditioning prompts of the sweep prompt length
(tag "exp6-conditioning-c{C}"), disjoint from the measured and warmup prompts.
They are run concurrently (max_num_seqs = C) BEFORE the 2 original warmup
requests, identically for BF16 and RABIT, and are never measured.
"""

from __future__ import annotations

import hashlib
import json

PROMPT_LENGTHS = (2048, 8192)
CONCURRENCY_GRID = (1, 4, 8, 16, 32, 64)
RABIT_EXTENSION_GRID = (128, 256)  # pre-registered; RABIT-only; NOT enabled until reviewed
MEASURED_REQUESTS = 256
WARMUP_REQUESTS = 2
OUTPUT_TOKENS = 32
TRIALS = 3
# Pre-registered counterbalanced dtype order per trial (fixed before any run).
TRIAL_DTYPE_ORDER = {1: ("bfloat16", "rabit_kv2"), 2: ("rabit_kv2", "bfloat16"), 3: ("bfloat16", "rabit_kv2")}
BOS = 128000
VOCAB_LO, VOCAB_HI = 1000, 30000


def _prompt(tag: str, length: int, index: int) -> list[int]:
    ids = [BOS]
    k = 0
    while len(ids) < length:
        h = hashlib.sha256(f"{tag}:{length}:{index}:{k}".encode("ascii")).digest()
        for j in range(0, 32, 4):
            if len(ids) == length:
                break
            ids.append(VOCAB_LO + int.from_bytes(h[j:j + 4], "big") % (VOCAB_HI - VOCAB_LO))
        k += 1
    return ids


def measured_prompts(length: int) -> list[list[int]]:
    return [_prompt("exp6-measured", length, i) for i in range(MEASURED_REQUESTS)]


def warmup_prompts(length: int) -> list[list[int]]:
    return [_prompt("exp6-warmup", length, i) for i in range(WARMUP_REQUESTS)]


def ids_sha256(ids) -> str:
    return hashlib.sha256(json.dumps(list(ids)).encode("utf-8")).hexdigest()


def set_digest(prompts: list[list[int]]) -> dict:
    per = [ids_sha256(p) for p in prompts]
    return {"count": len(per), "per_prompt_sha256": per,
            "ordered_set_sha256": hashlib.sha256("\n".join(per).encode("ascii")).hexdigest()}


def conditioning_prompts(length: int, concurrency: int) -> list[list[int]]:
    """Point-matched compile-conditioning: exactly C prompts of the sweep length (unmeasured)."""
    if concurrency < 1:
        raise ValueError("concurrency must be >= 1")
    return [_prompt(f"exp6-conditioning-c{concurrency}", length, i) for i in range(concurrency)]


def plan_points(length: int) -> list[dict]:
    """The pre-registered execution order for one prompt-length sweep: trial 1..3, dtype order per trial,
    ascending concurrency within each dtype."""
    out = []
    for trial in range(1, TRIALS + 1):
        for dtype in TRIAL_DTYPE_ORDER[trial]:
            for c in CONCURRENCY_GRID:
                out.append({"label": f"t{trial}_{'bf16' if dtype == 'bfloat16' else 'rabit'}_L{length}_c{c}",
                            "trial": trial, "dtype": dtype, "prompt_tokens": length, "concurrency": c})
    return out
